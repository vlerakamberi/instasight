def _alert_badge_color(alert_type: str) -> str:
    if alert_type in ("engagement_drop", "posting_inactivity"):
        return "#DC3545"
    if alert_type == "engagement_spike":
        return "#28A745"
    return "#6C757D"


def _get_username(account_id: str) -> str:
    try:
        with get_connection() as conn:
            row = conn.execute(
                "SELECT username FROM accounts WHERE id = ?",
                (account_id,),
            ).fetchone()
        if row and row["username"]:
            return row["username"]
    except Exception:  # noqa: BLE001 - fall back to id if lookup fails
        pass
    return account_id


def _render_alert_html(username: str, alerts: List[Dict[str, Any]]) -> str:
    cards = []
    for alert in alerts:
        color = _alert_badge_color(alert["alert_type"])
        label = alert["alert_type"].replace("_", " ").title()
        previous = alert.get("metric_previous")
        current = alert.get("metric_value")
        cards.append(
            f"""
            <div style="border:1px solid #E9ECEF; border-radius:10px;
                        padding:16px 18px; margin-bottom:14px;">
              <span style="background:{color}; color:#ffffff; font-size:0.72rem;
                           font-weight:700; padding:4px 12px; border-radius:20px;
                           text-transform:uppercase; letter-spacing:0.04em;">
                {label}
              </span>
              <p style="margin:14px 0 8px 0; color:#1A1A2E;">{alert['message']}</p>
              <div style="font-size:0.85rem; color:#6C757D;">
                Metric change: {previous}% → {current}%
              </div>
            </div>
            """
        )
    body = "\n".join(cards)
    now = datetime.now()
    return _ALERT_HTML_TEMPLATE.format(
        username=username,
        date=now.strftime("%Y-%m-%d"),
        timestamp=now.replace(microsecond=0).isoformat(),
        body=body,
    )


def _render_alert_text(username: str, alerts: List[Dict[str, Any]]) -> str:
    lines = [f"InstaSight Performance Alert for @{username}", ""]
    for alert in alerts:
        label = alert["alert_type"].replace("_", " ").title()
        lines.append(f"[{label}] {alert['message']}")
        lines.append(
            f"   Metric change: {alert.get('metric_previous')}% -> "
            f"{alert.get('metric_value')}%"
        )
        lines.append("")
    lines.append(f"InstaSight Automated Monitoring | {datetime.now().isoformat()}")
    return "\n".join(lines)


def send_alert_email(account_id: str, alerts: List[Dict[str, Any]]) -> bool:
    """
    Email a performance-alert digest to the configured Gmail address.

    Returns True on success, False on failure (including no alerts to send).
    """
    settings = load_settings()

    if not settings.gmail_address or not settings.gmail_app_password:
        logger.error(
            "Gmail credentials missing. Set GMAIL_ADDRESS and GMAIL_APP_PASSWORD in .env"
        )
        return False

    if not alerts:
        logger.info("No alerts to email for %s; skipping.", account_id)
        return False

    recipient_email = settings.gmail_address

    try:
        username = _get_username(account_id)
        subject = f"⚠️ InstaSight Alert — @{username} | {datetime.now().strftime('%Y-%m-%d')}"

        message = MIMEMultipart("alternative")
        message["Subject"] = Header(subject, "utf-8")
        message["From"] = settings.gmail_address
        message["To"] = recipient_email
        message.attach(MIMEText(_render_alert_text(username, alerts), "plain", "utf-8"))
        message.attach(MIMEText(_render_alert_html(username, alerts), "html", "utf-8"))

        with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=30) as server:
            server.starttls()
            server.login(settings.gmail_address, settings.gmail_app_password)
            server.send_message(message)

        logger.info(
            "Alert email sent to %s for @%s (%s alerts)",
            recipient_email,
            username,
            len(alerts),
        )
        return True
    except Exception as exc:  # noqa: BLE001 - report any send failure as False
        logger.error(
            "Failed to send alert email for %s: %s",
            account_id,
            exc,
        )
        return False
