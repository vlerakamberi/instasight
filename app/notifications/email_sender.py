def _render_html(plan: Dict[str, Any]) -> str:
    body_html = md.markdown(
        plan["plan"],
        extensions=["extra", "sane_lists", "nl2br"],
    )
    return _HTML_TEMPLATE.format(
        username=plan["username"],
        week_start=plan["week_start"],
        week_end=plan["week_end"],
        body=body_html,
    )


def send_weekly_plan_email(
    account_id: str,
    recipient_email: str,
    plan: Optional[Dict[str, Any]] = None,
) -> bool:
    """
    Generate (or reuse) the weekly plan and email it via Gmail SMTP.

    Returns True on success, False on failure. A pre-generated `plan` dict
    (as returned by generate_weekly_plan) can be passed to avoid a second
    Claude API call.
    """
    settings = load_settings()

    if not settings.gmail_address or not settings.gmail_app_password:
        logger.error(
            "Gmail credentials missing. Set GMAIL_ADDRESS and GMAIL_APP_PASSWORD in .env"
        )
        return False

    try:
        if plan is None:
            plan = generate_weekly_plan(account_id)

        username = plan["username"]
        subject = (
            f"📊 Weekly Instagram Growth Plan — @{username} | "
            f"{plan['week_start']} to {plan['week_end']}"
        )

        message = MIMEMultipart("alternative")
        message["Subject"] = Header(subject, "utf-8")
        message["From"] = settings.gmail_address
        message["To"] = recipient_email
        message.attach(MIMEText(plan["plan"], "plain", "utf-8"))
        message.attach(MIMEText(_render_html(plan), "html", "utf-8"))

        with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=30) as server:
            server.starttls()
            server.login(settings.gmail_address, settings.gmail_app_password)
            server.send_message(message)

        logger.info(
            "Weekly plan email sent to %s for @%s",
            recipient_email,
            username,
        )
        return True
    except Exception as exc:  # noqa: BLE001 - report any send failure as False
        logger.error(
            "Failed to send weekly plan email to %s: %s",
            recipient_email,
            exc,
        )
        return False


